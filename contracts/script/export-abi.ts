// Writes packages/protocol/src/abi.ts from forge artifacts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CONTRACTS = { stashPoolAbi: "StashPool", screeningGateAbi: "ScreeningGate", usdgAbi: "MockUSDG", bondsAbi: "Bonds" } as const;
const out = join(import.meta.dir, "..", "out");
let ts = "// Generated by contracts/script/export-abi.ts. Do not edit.\n";
for (const [name, contract] of Object.entries(CONTRACTS)) {
  const abi = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), "utf8")).abi;
  ts += `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(join(import.meta.dir, "..", "..", "packages", "protocol", "src", "abi.ts"), ts);
console.log("abi.ts written");
